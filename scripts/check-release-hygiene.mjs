import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { spawnSync } from "node:child_process";

function git(arguments_) {
  const result = spawnSync("git", arguments_, {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  assert.equal(result.status, 0, result.stderr || `git ${arguments_.join(" ")} failed`);
  return result.stdout;
}

const trackedFiles = git(["ls-files", "-z"]).split("\0").filter(Boolean);
const forbiddenTrackedPaths = [
  /(^|\/)\.DS_Store$/u,
  /(^|\/)\.env(?:\.|$)/u,
  /(^|\/)(?:coverage|dist|node_modules|test-results)(?:\/|$)/u,
  /\.(?:bak|log|orig|patch|rej|tgz|zip)$/iu,
];
for (const filePath of trackedFiles) {
  assert.equal(
    forbiddenTrackedPaths.some((pattern) => pattern.test(filePath)),
    false,
    `temporary, secret-bearing, or generated artifact must not be tracked: ${filePath}`,
  );
}

assert.equal(
  git(["ls-files", "-s", "-z"]).split("\0").filter(Boolean).some((entry) => entry.startsWith("120000 ")),
  false,
  "public source must not contain tracked symlinks",
);
assert.deepEqual(
  trackedFiles.filter((filePath) => /\.(?:gif|jpe?g|png|webp)$/iu.test(filePath)),
  [],
  "review every tracked raster asset explicitly",
);
assert.deepEqual(
  trackedFiles.filter((filePath) => /\.svg$/iu.test(filePath)).sort(),
  ["ui/favicon.svg"],
  "review every tracked SVG asset explicitly",
);

const patterns = [
  {
    category: "old product identity",
    values: [new RegExp(["standard", "expression", "interpreter"].join("-"), "iu")],
  },
  {
    category: "local absolute path",
    values: [
      /\/Users\/[^/\s]+\//u,
      /\/home\/[^/\s]+\//u,
      /C:\\Users\\[^\\\s]+\\/iu,
      /file:\/\/\/(?:Users|home)\//iu,
      /file:\/\/[A-Za-z]:\/Users\//iu,
    ],
  },
  {
    category: "likely secret",
    values: [
      /-----BEGIN (?:RSA |OPENSSH |EC )?PRIVATE KEY-----/u,
      new RegExp(`\\bgh(?:${["p", "o", "u", "s", "r"].join("|")})_[A-Za-z0-9_]{20,}\\b`, "u"),
      new RegExp(`\\b${["github", "pat"].join("_")}_[A-Za-z0-9_]{20,}\\b`, "iu"),
      new RegExp(`\\b${["s", "k"].join("")}-(?:proj-)?[A-Za-z0-9_-]{20,}\\b`, "u"),
      /\bAKIA[0-9A-Z]{16}\b/u,
      /\b(?:OPENAI_API_KEY|ANTHROPIC_API_KEY|AWS_SECRET_ACCESS_KEY)\s*[:=]\s*["']?[A-Za-z0-9_/+=.-]{12,}/u,
    ],
  },
  {
    category: "generated Agent work trace",
    values: [
      new RegExp(`Generated by (?:${["Codex", "ChatGPT", "Claude"].join("|")})`, "iu"),
      /\bagent[-_ ]?(?:session|trace)\b/iu,
    ],
  },
];

function assertCleanText(text, subject, activePatterns = patterns) {
  for (const { category, values } of activePatterns) {
    assert.equal(
      values.some((pattern) => pattern.test(text)),
      false,
      `${category} found in ${subject}`,
    );
  }
}

for (const filePath of trackedFiles) {
  const content = readFileSync(filePath);
  if (!content.includes(0)) assertCleanText(content.toString("utf8"), `tracked text: ${filePath}`);
}
assertCleanText(
  git(["log", "--format=%B", "-p", "--no-ext-diff", "HEAD"]),
  "reachable Git history",
  // The public rename commit necessarily records the superseded package name;
  // history stays strict for credentials, local paths, and Agent traces.
  patterns.filter(({ category }) => category !== "old product identity"),
);

process.stdout.write("Public release hygiene checks passed.\n");
